"""Task submission and status schemas."""

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, Optional
from pydantic import BaseModel, Field, field_validator


class TaskStatus(str, Enum):
    """Execution status states for a submitted agent task."""

    PENDING = "pending"
    EXECUTING = "executing"
    COMPLETED = "completed"
    FAILED = "failed"
    CANCELLED = "cancelled"
    LIMIT_REACHED = "limit_reached"


class TaskCreateRequest(BaseModel):
    """User prompt submission request payload."""

    prompt: str = Field(
        ...,
        min_length=1,
        max_length=32768,
        description="The task instructions or user prompt to be processed",
    )
    max_tokens: Optional[int] = Field(
        default=2048,
        ge=1,
        le=8192,
        description="Maximum tokens requested from the model",
    )
    temperature: Optional[float] = Field(
        default=0.2,
        ge=0.0,
        le=2.0,
        description="Sampling temperature for the generation",
    )
    system_prompt: Optional[str] = Field(
        default=None,
        description="Optional custom system prompt directive for the agent",
    )
    session_id: Optional[str] = Field(
        default=None,
        description="Optional session UUID to which this task belongs",
    )

    @field_validator("prompt")
    @classmethod
    def validate_non_whitespace(cls, v: str) -> str:
        """Reject empty or whitespace-only prompt strings."""
        stripped = v.strip()
        if not stripped:
            raise ValueError("Prompt cannot be empty or contain only whitespace characters")
        return stripped


class TaskResponse(BaseModel):
    """Standardized task result and execution summary response."""

    task_id: str = Field(..., description="Unique identifier for the task (UUID)")
    session_id: Optional[str] = Field(
        default=None,
        description="Optional session UUID to which this task belongs",
    )
    prompt: str = Field(..., description="The original submitted prompt")
    status: TaskStatus = Field(..., description="Current execution status of the task")
    recovery_status: Optional[str] = Field(
        default=None,
        description="Recovery classification (e.g. clean, interrupted_safe, needs_review)",
    )
    response_text: Optional[str] = Field(
        default=None,
        description="Normalized textual response generated by the model",
    )
    finish_reason: Optional[str] = Field(
        default=None,
        description="Reason generation terminated (e.g., stop, length, error)",
    )
    model: Optional[str] = Field(
        default=None,
        description="Model identifier that produced the completion",
    )
    usage: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Token utilization metrics reported by the model provider",
    )
    error: Optional[str] = Field(
        default=None,
        description="Actionable error description if execution failed",
    )
    iterations: Optional[int] = Field(
        default=None,
        description="Total multi-turn iteration cycles executed",
    )
    tool_calls_count: Optional[int] = Field(
        default=None,
        description="Total tool calls executed during the task",
    )
    termination_reason: Optional[str] = Field(
        default=None,
        description="Explicit terminal condition reason (e.g., 'completed', 'cancelled', 'max_iterations')",
    )
    created_at: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="ISO 8601 UTC creation timestamp",
    )
    completed_at: Optional[str] = Field(
        default=None,
        description="ISO 8601 UTC completion timestamp",
    )
